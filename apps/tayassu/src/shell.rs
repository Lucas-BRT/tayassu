use clap::ValueEnum;
use clap_complete::CompletionCandidate;
use std::fmt::Write as _;
use tayassu_core::ProviderKind;
use tayassu_store::{AppConfig, XdgPaths};

/// Default providers wrapped by `tayassu shell-init` when `--provider` is omitted.
pub const DEFAULT_SHELL_PROVIDERS: &[ProviderKind] = &[
    ProviderKind::Agy,
    ProviderKind::Claude,
    ProviderKind::Codex,
    ProviderKind::Copilot,
    ProviderKind::Opencode,
];

/// Target shell syntax supported by `tayassu shell-init`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub enum ShellKind {
    /// GNU Bash (`~/.bashrc`).
    Bash,
    /// Zsh (`~/.zshrc`).
    Zsh,
    /// Fish (`~/.config/fish/config.fish`).
    Fish,
}

/// Environment variable used by the generated shell completers.
pub const COMPLETION_ENV: &str = "TAYASSU_COMPLETE";

fn load_completion_config() -> Option<AppConfig> {
    let paths = XdgPaths::from_env().ok()?;
    AppConfig::load(&paths.config_file).ok()
}

pub fn account_candidates() -> Vec<CompletionCandidate> {
    load_completion_config().map_or_else(Vec::new, |config| {
        config
            .accounts
            .into_iter()
            .map(|account| {
                CompletionCandidate::new(account.id.to_string()).help(Some(account.label.into()))
            })
            .collect()
    })
}

pub fn chain_candidates() -> Vec<CompletionCandidate> {
    load_completion_config().map_or_else(Vec::new, |config| {
        config
            .fallback_chains
            .into_keys()
            .map(CompletionCandidate::new)
            .collect()
    })
}

pub fn provider_candidates() -> Vec<CompletionCandidate> {
    DEFAULT_SHELL_PROVIDERS
        .iter()
        .copied()
        .chain([ProviderKind::Custom])
        .map(|provider| CompletionCandidate::new(provider.as_str()))
        .collect()
}

/// Generates shell wrapper functions that route AI CLI invocations through `tayassu run`.
#[derive(Debug, Clone)]
pub struct ShellInit {
    shell: ShellKind,
    providers: Vec<ProviderKind>,
    failover: bool,
}

impl ShellInit {
    /// Creates a new [`ShellInit`] generator.
    #[must_use]
    pub fn new(shell: ShellKind, providers: Vec<ProviderKind>, failover: bool) -> Self {
        let resolved = if providers.is_empty() {
            DEFAULT_SHELL_PROVIDERS.to_vec()
        } else {
            providers
        };
        Self {
            shell,
            providers: resolved,
            failover,
        }
    }

    /// Renders the shell snippet ready for `eval` or sourcing.
    #[must_use]
    pub fn render(&self) -> String {
        let mut out = String::new();
        let failover_flag = if self.failover { " --failover" } else { "" };

        let _ = writeln!(
            out,
            "# Generated by `tayassu shell-init`. Bypass any wrapper with `command <cli> ...`."
        );

        match self.shell {
            ShellKind::Bash => {
                let _ = writeln!(out, "eval \"$({COMPLETION_ENV}=bash tayassu)\"");
            }
            ShellKind::Zsh => {
                let _ = writeln!(out, "eval \"$({COMPLETION_ENV}=zsh tayassu)\"");
            }
            ShellKind::Fish => {
                let _ = writeln!(out, "env {COMPLETION_ENV}=fish tayassu | source");
            }
        }

        for &provider in &self.providers {
            let cmd = provider.default_binary();
            let name = provider.as_str();
            match self.shell {
                ShellKind::Bash | ShellKind::Zsh => {
                    let _ = writeln!(
                        out,
                        "{cmd}() {{ tayassu run {name}{failover_flag} -- \"$@\"; }}"
                    );
                }
                ShellKind::Fish => {
                    let _ = writeln!(
                        out,
                        "function {cmd} --wraps {cmd}\n    tayassu run {name}{failover_flag} -- $argv\nend"
                    );
                }
            }
        }

        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_bash_and_fish_wrappers_with_optional_failover() {
        let bash = ShellInit::new(
            ShellKind::Bash,
            vec![ProviderKind::Agy, ProviderKind::Claude],
            true,
        )
        .render();
        assert!(bash.contains("agy() { tayassu run agy --failover -- \"$@\"; }"));
        assert!(bash.contains("claude() { tayassu run claude --failover -- \"$@\"; }"));

        let fish = ShellInit::new(ShellKind::Fish, vec![ProviderKind::Codex], false).render();
        assert!(fish.contains("function codex --wraps codex"));
        assert!(fish.contains("tayassu run codex -- $argv"));
    }
}
